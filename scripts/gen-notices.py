#!/usr/bin/env python3
"""THIRD_PARTY_NOTICES.md(목록)와 THIRD_PARTY_LICENSES.txt(라이선스 전문)를 만든다.
의존성이 바뀌면 다시 실행한다. THIRD_PARTY_LICENSES.txt는 앱 설치 파일에 함께 들어간다.

사용법: python3 scripts/gen-notices.py
"""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

meta = json.loads(
    subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT / "src-tauri",
    )
)
ids = {n["id"] for n in meta["resolve"]["nodes"]}
pkgs = [p for p in meta["packages"] if p["id"] in ids and p["name"] != "plugin-hub"]
crates = sorted({(p["name"], p["version"], p.get("license") or "UNKNOWN", p.get("repository") or "") for p in pkgs})

lock = json.loads((ROOT / "package-lock.json").read_text())
npm = sorted(
    (k.replace("node_modules/", ""), v.get("version", ""), v.get("license", "UNKNOWN"))
    for k, v in lock["packages"].items()
    if k and not v.get("dev")
)

copyleft = [c for c in crates if "MPL" in c[2]]

lines = [
    "# Third-Party Notices",
    "",
    "Plugin Hub는 아래 오픈소스 소프트웨어를 포함해 배포합니다. 각 소프트웨어의 저작권은 해당 저작자에게 있으며,",
    "라이선스 전문은 THIRD_PARTY_LICENSES.txt(앱에도 포함)에 있습니다. 이 파일은 `scripts/gen-notices.py`로 생성합니다.",
    "",
    "Plugin Hub includes the open-source software listed below. Copyright belongs to the respective authors;",
    "full license texts are included in THIRD_PARTY_LICENSES.txt (also bundled with the app). Generated by `scripts/gen-notices.py`.",
    "",
    "## MPL-2.0 구성 요소 / MPL-2.0 components",
    "",
    "다음 구성 요소는 Mozilla Public License 2.0을 따르며, 수정 없이 사용합니다. 소스 코드는 각 저장소에서 받을 수 있습니다.",
    "The following components are used unmodified under the Mozilla Public License 2.0; source code is available from each repository.",
    "",
]
lines += [f"- {n} {v} ({lic}) {repo}".rstrip() for n, v, lic, repo in copyleft]
lines += ["", f"## Rust crates ({len(crates)})", "", "| Crate | Version | License |", "|---|---|---|"]
lines += [f"| {n} | {v} | {lic} |" for n, v, lic, _ in crates]
lines += ["", f"## npm packages ({len(npm)})", "", "| Package | Version | License |", "|---|---|---|"]
lines += [f"| {n} | {v} | {lic} |" for n, v, lic in npm]
lines += [
    "",
    "## 데이터 / Data",
    "",
    "- 인기도(`src/data/popularity.json`): GitHub 공개 저장소의 스타 수를 2026-11-20에 수집한 스냅샷입니다.",
    "- 한국어 요약(`src/data/ko-catalog.json`): 각 플러그인이 공개한 설명을 바탕으로 이 프로젝트가 작성한 요약입니다.",
    "",
]
(ROOT / "THIRD_PARTY_NOTICES.md").write_text("\n".join(lines))

# ---- 라이선스 전문: 각 패키지가 배포한 LICENSE/COPYING/NOTICE 파일을 모으고, 같은 내용은 한 번만 싣는다
import hashlib

PATTERNS = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE", "COPYRIGHT")


def license_files(d: Path):
    if not d.is_dir():
        return []
    out = []
    for f in sorted(d.iterdir()):
        if f.is_file() and f.name.upper().startswith(PATTERNS) and f.stat().st_size < 200_000:
            out.append(f)
    return out


groups = {}  # hash -> (text, [names])
missing = []
entries = [(f"{p['name']} {p['version']} ({p.get('license') or 'UNKNOWN'})", Path(p["manifest_path"]).parent) for p in pkgs]
entries += [
    (f"{n} {v} ({lic}) [npm]", ROOT / "node_modules" / n) for n, v, lic in npm
]
for label, d in sorted(entries):
    files = license_files(d)
    if not files:
        missing.append(label)
        continue
    for f in files:
        text = f.read_text(errors="replace").strip()
        h = hashlib.sha256(text.encode()).hexdigest()
        groups.setdefault(h, (f.name, text, []))[2].append(label)

out = [
    "Plugin Hub - Third-party licenses",
    "=" * 40,
    "",
    "이 파일에는 Plugin Hub에 포함된 오픈소스 소프트웨어의 라이선스 전문이 들어 있습니다.",
    "This file contains the full license texts of open-source software included in Plugin Hub.",
    "",
]
for name, text, labels in sorted(groups.values(), key=lambda g: g[2][0]):
    out += ["-" * 72, f"{name} -- used by:"] + [f"  {l}" for l in labels] + ["", text, ""]
if missing:
    out += [
        "-" * 72,
        "The following packages do not ship a license file in their published package.",
        "They are distributed under the SPDX license shown. The standard text of each of these licenses",
        "(MIT, Apache-2.0, BSD-3-Clause, Zlib) appears in full in the sections above; copyright notices",
        "are in each project's repository:",
    ] + [f"  {m}" for m in missing]
(ROOT / "THIRD_PARTY_LICENSES.txt").write_text("\n".join(out) + "\n")
print(f"license texts: {len(groups)} unique, {len(missing)} packages without a license file")
print(f"crates={len(crates)} npm={len(npm)} mpl={len(copyleft)}")
